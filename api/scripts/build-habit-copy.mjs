#!/usr/bin/env node
// Writes api/habit-copy.js, the server's copy of the daily-habit push text, from the source of
// truth in the frontend: HABIT_PUSH in frontend/src/lib/habits.js and its translations in
// frontend/src/locales. Same idea as build-nudge-copy.mjs (test/habit-copy.test.js fails when the
// two have drifted).
//
//   node scripts/build-habit-copy.mjs          # rewrite habit-copy.js
//   node scripts/build-habit-copy.mjs --check  # exit 1 if it is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const API = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const FRONT = path.join(API, '..', 'frontend', 'src');
const OUT = path.join(API, 'habit-copy.js');

export async function buildHabitCopy() {
  const { HABIT_PUSH } = await import(pathToFileURL(path.join(FRONT, 'lib', 'habits.js')));
  const langs = fs.readdirSync(path.join(FRONT, 'locales')).filter(f => /^[a-zA-Z-]+\.js$/.test(f)).map(f => f.slice(0, -3)).sort();
  const copy = { en: HABIT_PUSH };
  for (const lang of langs) {
    const pack = (await import(pathToFileURL(path.join(FRONT, 'locales', lang + '.js')))).default;
    copy[lang] = Object.fromEntries(Object.entries(HABIT_PUSH).map(([k, s]) => [k, pack[s] || s]));
  }
  return '// GENERATED by scripts/build-habit-copy.mjs from frontend/src/lib/habits.js and frontend/src/locales.\n'
    + '// Do not edit by hand: change the frontend strings and run the script again.\n'
    + 'export const HABIT_COPY = ' + JSON.stringify(copy, null, 2) + ';\n';
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = await buildHabitCopy();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (cur !== text) { console.error('api/habit-copy.js is out of date: run node scripts/build-habit-copy.mjs'); process.exit(1); }
    console.log('api/habit-copy.js is up to date.');
  } else {
    fs.writeFileSync(OUT, text);
    console.log('wrote', path.relative(process.cwd(), OUT));
  }
}
